// Room-core contract (docs/05-tech-stack.md section 7). Implemented by WS3a, driven by WS3b.
import type { EngineState, GameEvent, Mode } from '@dbay/engine';
import type { ClientAction, PlayerId, ServerMsg } from '@dbay/protocol';

export type Phase = 'lobby' | 'playing' | 'reveal' | 'ended';

export interface RoomPlayer {
  id: PlayerId;
  name: string;
  seat: number;
  isBot: boolean;
  /** SHA-256 hex of the seat secret. Bots have none. Never sent to clients. */
  secretHash: string | null;
  connected: boolean;
  /** Join order, for host migration (longest-connected human). */
  joinedAt: number;
  lastSeen: number;
  /** Highest action seq processed (05 section 6.5). */
  lastSeq: number;
}

export interface Deadline {
  at: number;
  kind: 'engine' | 'expire' | 'hostCheck' | 'disconnect' | 'reveal' | 'bot';
  data?: string;
}

export interface RoomState {
  meta: {
    code: string;
    schemaVersion: number;
    createdAt: number;
    expireAt: number;
    hostId: PlayerId | null;
    phase: Phase;
    opts: { mode: Mode; relaxed: boolean; bidWindowMs: number };
    /** Hashes of banned secrets plus banned playerIds. */
    banned: string[];
  };
  players: RoomPlayer[];
  game: EngineState | null;
  /** Numbered game log; the view shows the last 30. */
  log: Array<GameEvent & { n: number }>;
  /** Sorted ascending by `at`. */
  deadlines: Deadline[];
  rev: number;
}

/** Inputs to the reducer. The DO wrapper produces these; `now` is passed separately. */
export type RoomEvent =
  /** A new socket sent `join`. `secret`/`secretHash` are generated by the wrapper (crypto lives there). */
  | { type: 'join'; conn: string; name: string; playerId: PlayerId; secret: string; secretHash: string }
  /** A socket sent `hello`; the wrapper already hashed the presented secret. */
  | { type: 'hello'; conn: string; playerId: PlayerId; secretHash: string }
  | { type: 'action'; playerId: PlayerId; msg: ClientAction }
  | { type: 'leave'; playerId: PlayerId }
  | { type: 'connect'; conn: string }
  | { type: 'disconnect'; playerId: PlayerId }
  | { type: 'snap'; playerId: PlayerId }
  /** Alarm fired: run every deadline <= now. */
  | { type: 'tick' }
  /** Seed for a new game, generated by the wrapper with crypto before a `start` action. */
  | { type: 'seed'; seed: string };

export type Effect =
  | { type: 'send'; to: PlayerId | 'all' | { conn: string }; msg: ServerMsg }
  /** Send each player their own redacted snapshot (built via `view`). */
  | { type: 'broadcastSnapshots' }
  | { type: 'setAlarm'; at: number | null }
  | { type: 'persist' }
  | { type: 'closeSocket'; playerId: PlayerId; why: 'kicked' | 'replaced' | 'expired' | 'banned' }
  | { type: 'deleteRoom' }
  | { type: 'log'; entry: { room: string; event: string; rev: number } };

export interface ReduceResult {
  state: RoomState;
  effects: Effect[];
}
