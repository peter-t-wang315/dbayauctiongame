// Room-core contract (docs/05-tech-stack.md section 7). Implemented by WS3a, driven by WS3b.
// Additions made by WS3a over the WS0 stub are all OPTIONAL fields / optional params (additive).
import type { EngineState, GameEvent, Mode } from '@dbay/engine';
import type { ClientAction, GameLength, PlayerId, ServerMsg } from '@dbay/protocol';

export type Phase = 'lobby' | 'playing' | 'reveal' | 'ended';

export interface RoomPlayer {
  id: PlayerId;
  name: string;
  seat: number;
  isBot: boolean;
  /** SHA-256 hex of the seat secret. Bots have none. Never sent to clients. */
  secretHash: string | null;
  connected: boolean;
  /** Join order, for host migration (longest-connected human). */
  joinedAt: number;
  lastSeen: number;
  /** Highest action seq processed (05 section 6.5). */
  lastSeq: number;
  /** When this human was last marked disconnected (drives host migration, 05 section 8). */
  disconnectedAt?: number;
}

export interface Deadline {
  at: number;
  kind: 'engine' | 'expire' | 'hostCheck' | 'disconnect' | 'reveal' | 'bot';
  data?: string;
}

export interface RoomOpts {
  mode: Mode;
  relaxed: boolean;
  bidWindowMs: number;
  /** Game length preset; absent means 'standard'. */
  length?: GameLength;
}

export interface RoomState {
  meta: {
    code: string;
    schemaVersion: number;
    createdAt: number;
    /** Effective expiry (base expiry, shortened to 10 min after the last human drops). */
    expireAt: number;
    hostId: PlayerId | null;
    phase: Phase;
    opts: RoomOpts;
    /** Hashes of banned secrets plus banned playerIds. */
    banned: string[];
    /** Seed supplied by the wrapper (`seed` event) for the next `start`. SECRET; never in a view. */
    seed?: string;
    /** Phase-based expiry before the all-disconnected shortening. */
    baseExpireAt?: number;
    /** Set while every human is disconnected (05 section 8). */
    allDownAt?: number;
    /** When `reveal` flips to `ended` (01 R37). */
    revealAt?: number;
    /** Time of the last state-changing event (lets `view` judge cooldowns without a clock). */
    updatedAt?: number;
    /** True once the host explicitly chose a mode via setOpts; then it sticks (02). */
    modeSet?: boolean;
    /** Last game-log number issued. */
    logN?: number;
    /** True once the room expired. Further events get ROOM_NOT_FOUND. */
    closed?: boolean;
  };
  players: RoomPlayer[];
  game: EngineState | null;
  /** Numbered game log; the view shows the last 30. */
  log: Array<GameEvent & { n: number }>;
  /** Sorted ascending by `at`. */
  deadlines: Deadline[];
  rev: number;
}

/** Inputs to the reducer. The DO wrapper produces these; `now` is passed separately. */
export type RoomEvent =
  /** A new socket sent `join`. `secret`/`secretHash` are generated by the wrapper (crypto lives there). */
  | {
      type: 'join';
      conn: string;
      name: string;
      playerId: PlayerId;
      secret: string;
      secretHash: string;
    }
  /** A socket sent `hello`; the wrapper already hashed the presented secret. */
  | { type: 'hello'; conn: string; playerId: PlayerId; secretHash: string }
  | { type: 'action'; playerId: PlayerId; msg: ClientAction }
  | { type: 'leave'; playerId: PlayerId }
  | { type: 'connect'; conn: string }
  | { type: 'disconnect'; playerId: PlayerId }
  | { type: 'snap'; playerId: PlayerId }
  /** Alarm fired: run every deadline <= now. */
  | { type: 'tick' }
  /** Seed for a new game, generated by the wrapper with crypto before a `start` action. */
  | { type: 'seed'; seed: string };

export type Effect =
  | { type: 'send'; to: PlayerId | 'all' | { conn: string }; msg: ServerMsg }
  /** Send each player their own redacted snapshot (built via `view`). Unused by room-core itself (it emits explicit `snap` sends). */
  | { type: 'broadcastSnapshots' }
  | { type: 'setAlarm'; at: number | null }
  | { type: 'persist' }
  /**
   * Close the player's sockets. With `exceptConn`, keep that connection open (used for
   * `replaced`: the new socket that just sent `hello` must survive).
   */
  | {
      type: 'closeSocket';
      playerId: PlayerId;
      why: 'kicked' | 'replaced' | 'expired' | 'banned';
      exceptConn?: string;
    }
  | { type: 'deleteRoom' }
  | { type: 'log'; entry: { room: string; event: string; rev: number } };

export interface ReduceResult {
  state: RoomState;
  effects: Effect[];
}
